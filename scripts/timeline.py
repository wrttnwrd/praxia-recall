#!/usr/bin/env python3
"""Generate timeline.md — every dated concept in Praxian chronological order."""
import re, sys, collections
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from graphlib import load_graph
from urllib.parse import quote
import yaml

B = Path(__file__).resolve().parent.parent
CAL = yaml.safe_load((B / "calendar.yaml").read_text(encoding="utf-8"))
G = load_graph()
MONTH = {m["name"].lower(): m["order"] for m in CAL["months"]}
for a, r in (CAL.get("aliases") or {}).items():
    MONTH[a.lower()] = MONTH[r.lower()]

def key(s):
    """Sortable (year, month, day) from a praxian_date string."""
    s = str(s)
    m = re.match(r"^(\d{1,2})\s+([A-Za-z' ]+?)\s+(-?\d{1,4})\s*FR", s)
    if m:
        return (int(m.group(3)), MONTH.get(m.group(2).strip().lower(), 0), int(m.group(1)))
    m = re.search(r"(-?[\d]+)\s*FR", s)
    if m:
        return (int(m.group(1)), 0, 0)
    m = re.search(r"(\d+)\s*BR", s)
    if m:
        return (-int(m.group(1)), 0, 0)
    return (9999, 0, 0)

rows = [(key(c["praxian_date"]), c) for c in G["concepts"] if c.get("praxian_date")]
rows.sort(key=lambda r: r[0])

L = ["---", "type: reference", "title: Timeline",
     "description: Every dated concept in Praxian chronological order.",
     "status: draft", "---", "", "# Timeline", "",
     f"{len(rows)} dated concepts. Generated by `scripts/timeline.py` from the "
     "`praxian_date` fields; the calendar is in [calendar.yaml](calendar.yaml).", "",
     "`occurred` = the in-world date it happened · `founded` = an `established:` "
     "date from the source · `first_seen` = the earliest dated session naming it "
     "(first mention, not necessarily first existence).", ""]

era = None
for k, c in rows:
    yr = k[0]
    e = ("Before the Fall" if yr < 0 else "The Fall" if yr == 0 else f"Year {yr:02d} FR")
    if e != era:
        era = e
        L += ["", f"## {era}", ""]
    basis = c.get("praxian_date_basis", "occurred")
    mark = {"occurred": "", "founded": " *(founded)*", "first_seen": " *(first mention)*"}[basis]
    L.append(f"* **{c['praxian_date']}** — [{c['title']}](world/{quote(c['kind'])}/{quote(c['id'])}.md) "
             f"· `{c['type']}`{mark}")

(B / "timeline.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"timeline.md — {len(rows)} dated concepts, {rows[0][1]['praxian_date']} → {rows[-1][1]['praxian_date']}")
