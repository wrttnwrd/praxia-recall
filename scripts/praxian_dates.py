#!/usr/bin/env python3
"""Derive a `praxian_date` for every concept and emit it as a graph.yaml block.

Three ways a concept gets one, in order of preference:

  occurred   the in-world date the thing happened — sessions take their own
             game_date; events take the date recorded in the graph.
  founded    an `established:` date stated in the source frontmatter, for
             concepts that came into being at a known time.
  first_seen the earliest game_date of any session whose text names the concept.
             This is "first mention in the record", not necessarily first
             existence, and is labelled as such.

Writes graph-dates.yaml for review, and appends nothing on its own.
Usage: python3 scripts/praxian_dates.py [--write]
"""
import re, sys, collections
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from graphlib import load_graph
import yaml

B = Path(__file__).resolve().parent.parent
CAL = yaml.safe_load((B / "calendar.yaml").read_text(encoding="utf-8"))
G = load_graph(with_dates=False)   # never read our own output
SRC = Path(G["source"]).expanduser()

MONTH = {m["name"].lower(): m["order"] for m in CAL["months"]}
for a, real in (CAL.get("aliases") or {}).items():
    MONTH[a.lower()] = MONTH[real.lower()]
MONTH_NAME = {m["order"]: m["name"] for m in CAL["months"]}

DATE_RE = re.compile(r"^\s*(\d{1,2})\s+([A-Za-z' ]+?)\s+(-?\d{1,4})\s*$")

def parse_game_date(s):
    """'23 Stormclaw 07' -> (year, month_order, day, pretty). None if unparseable."""
    if not s:
        return None
    s = str(s).strip()
    m = DATE_RE.match(s)
    if not m:
        return None
    day, mon, yr = int(m.group(1)), m.group(2).strip().lower(), int(m.group(3))
    if mon not in MONTH:
        return None
    return (yr, MONTH[mon], day, f"{day} {MONTH_NAME[MONTH[mon]]} {yr:02d} FR")

FR_RE = re.compile(r"(-?[\d,]+)\s*(?:FR|fr)\b")
BR_RE = re.compile(r"\b(?:BR|br)\s*(\d+)")

def parse_year(s):
    """'-300 fr' / 'BR 95' / '1 FR' -> (year, pretty)."""
    if not s:
        return None
    s = str(s).strip()
    m = FR_RE.search(s)
    if m:
        try:
            y = int(m.group(1).replace(",", ""))
        except ValueError:
            return None
        return (y, f"{y} FR")
    m = BR_RE.search(s)
    if m:
        y = -int(m.group(1))
        return (y, f"{m.group(1)} BR")
    return None

def fm_of(rel):
    p = SRC / rel
    if not p.exists():
        return {}
    m = re.match(r"\A---\n(.*?)\n---\n", p.read_text(errors="replace"), re.S)
    if not m:
        return {}
    try:
        fm = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError:
        # Templates and half-written notes carry frontmatter that is not YAML
        # (e.g. `name: {{title}}`). Treat them as having no frontmatter.
        return {}
    return fm if isinstance(fm, dict) else {}

def body_of(rel):
    p = SRC / rel
    if not p.exists():
        return ""
    raw = p.read_text(errors="replace")
    m = re.match(r"\A---\n.*?\n---\n", raw, re.S)
    return raw[m.end():] if m else raw

def main():
    # 1. every dated session, sorted
    sessions = []
    for c in G["concepts"]:
        if not c.get("source"):
            continue
        gd = parse_game_date(fm_of(c["source"]).get("game_date"))
        if gd:
            sessions.append((gd, c["id"], c["source"]))
    sessions.sort()

    # 2. first mention: earliest session naming the concept
    texts = [(gd, body_of(src).lower()) for gd, _, src in sessions]
    first_seen = {}
    for c in G["concepts"]:
        if c["kind"] == "sessions":
            continue
        names = [c["title"]] + (c.get("aka") or [])
        names = [n for n in names if len(n) > 3 and "(" not in n]
        if not names:
            continue
        for gd, txt in texts:
            if any(n.lower() in txt for n in names):
                first_seen[c["id"]] = gd
                break

    # a date stated by hand in graph.yaml always wins over a derived one
    stated = {c["id"] for c in G["concepts"] if c.get("praxian_date")}
    out, stats = [], collections.Counter()
    for c in G["concepts"]:
        if c["id"] in stated:
            continue
        entry, basis, pretty = None, None, None
        if c["kind"] == "sessions" and c.get("source"):
            gd = parse_game_date(fm_of(c["source"]).get("game_date"))
            if gd:
                entry, basis, pretty = gd, "occurred", gd[3]
        if entry is None and c.get("source"):
            est = parse_year(fm_of(c["source"]).get("established"))
            if est:
                entry, basis, pretty = (est[0], 0, 0, est[1]), "founded", est[1]
        if entry is None and c["id"] in first_seen:
            gd = first_seen[c["id"]]
            entry, basis, pretty = gd, "first_seen", gd[3]
        if entry is None:
            continue
        stats[basis] += 1
        out.append({"id": c["id"], "praxian_date": pretty, "praxian_date_basis": basis})

    txt = ("# Generated by scripts/praxian_dates.py — do not hand-edit.\n"
           "# basis: occurred = the in-world date it happened; founded = an\n"
           "# `established:` date stated in the source; first_seen = the earliest\n"
           "# dated session whose text names it (first mention, not first existence).\n"
           "concepts:\n"
           + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=100))
    (B / "graph-dates.yaml").write_text(txt, encoding="utf-8")
    print(f"dated {len(out)} of {len(G['concepts'])} concepts: " +
          ", ".join(f"{k}={v}" for k, v in stats.most_common()))
    print(f"session span: {sessions[0][0][3]} → {sessions[-1][0][3]}" if sessions else "")

main()
